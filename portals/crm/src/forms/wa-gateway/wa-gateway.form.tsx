import { useMemo } from 'react';
import { Controller, useForm } from 'react-hook-form';
import { zodResolver } from '@hookform/resolvers/zod';
import { Alert, Stack, TextField } from '@mui/material';
import KeyIcon from '@mui/icons-material/Key';
import { DuncitButton } from '@duncit/buttons';
import { fireAndForget, logs } from '@duncit/logs';
import { useTranslation } from '@duncit/shell';
import { WA_API_KEY_MAX, waGatewaySchema } from './wa-gateway.schema';
import type { WaGatewayFormProps, WaGatewayFormValues } from './wa-gateway.types';

/** Step 1 of the WhatsApp Lead Generator: gateway URL + API key (typed, or generated by the server). */
export default function WaGatewayForm({
  initialBaseUrl,
  hasKey,
  submitting,
  generating,
  error,
  notice,
  onSubmit,
  onGenerate,
}: Readonly<WaGatewayFormProps>) {
  const { t } = useTranslation();
  const schema = useMemo(() => waGatewaySchema(t, hasKey), [t, hasKey]);
  const {
    control,
    handleSubmit,
    trigger,
    getValues,
    formState: { errors },
  } = useForm<WaGatewayFormValues>({
    resolver: zodResolver(schema),
    mode: 'onSubmit',
    defaultValues: { base_url: initialBaseUrl, api_key: '' },
  });
  const busy = !!submitting || !!generating;

  // Generating needs only a valid URL, so it checks that one field rather than the whole form.
  const generate = () =>
    fireAndForget(
      trigger('base_url').then(async (valid) => {
        if (valid) await onGenerate(getValues('base_url').trim());
      }),
      logs.portal['crm'],
      'WaGatewayForm',
      'generate',
    );

  return (
    <form onSubmit={handleSubmit(onSubmit)} noValidate data-testid="wa-gateway-form">
      <Stack spacing={2}>
        {error && <Alert severity="error">{error}</Alert>}
        {!error && notice && <Alert severity="success">{notice}</Alert>}
        <Controller
          name="base_url"
          control={control}
          render={({ field }) => (
            <TextField
              {...field}
              size="small"
              type="url"
              label={t('crm.tools.gatewayUrl')}
              required
              fullWidth
              autoComplete="url"
              error={!!errors.base_url}
              helperText={errors.base_url?.message ?? t('crm.tools.gatewayUrlHint')}
              slotProps={{ htmlInput: { 'data-testid': 'wa-gateway-url' } }}
            />
          )}
        />
        <Controller
          name="api_key"
          control={control}
          render={({ field }) => (
            <TextField
              {...field}
              size="small"
              type="password"
              label={t('crm.tools.apiKey2')}
              required={!hasKey}
              fullWidth
              autoComplete="off"
              placeholder={hasKey ? t('crm.tools.apiKeyKeepPlaceholder') : t('crm.tools.apiKeyPlaceholder')}
              error={!!errors.api_key}
              helperText={errors.api_key?.message}
              slotProps={{ htmlInput: { 'data-testid': 'wa-gateway-key', maxLength: WA_API_KEY_MAX + 20 } }}
            />
          )}
        />
        <Stack direction={{ xs: 'column', sm: 'row' }} spacing={1.5} sx={{ justifyContent: 'flex-end' }}>
          <DuncitButton variant="outlined" startIcon={<KeyIcon />} loading={generating} disabled={busy} onClick={generate}>
            {t('crm.tools.generateApiKey')}
          </DuncitButton>
          <DuncitButton type="submit" variant="contained" loading={submitting} disabled={busy} data-testid="wa-gateway-submit">
            {t('crm.tools.saveAndContinue')}
          </DuncitButton>
        </Stack>
      </Stack>
    </form>
  );
}
