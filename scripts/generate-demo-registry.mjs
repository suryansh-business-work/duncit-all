#!/usr/bin/env node
/**
 * Writes `packages/docs-demos/src/registry.ts` from the demo files on disk.
 *
 * The registry is generated rather than hand-kept because it is pure
 * bookkeeping — 48 pairs of dynamic imports, one per package — and a hand-kept
 * list is exactly the sort of thing that silently loses an entry. `--check`
 * makes CI fail on a demo added without regenerating, the same contract
 * `generate-shipped-keys.mjs` holds for localization.
 *
 * The imports are written out one by one instead of an `import.meta.glob`: two
 * different bundlers consume this package (the Tech portal's Vite build and the
 * docs site's Astro/Vite build), and an explicit `import()` is something both
 * can code-split without any glob semantics to agree on. It also means a
 * missing file is a TypeScript error rather than an empty object at runtime.
 */
import fs from 'node:fs';
import path from 'node:path';

const ROOT = path.resolve(import.meta.dirname, '..');
const DEMO_DIR = path.join(ROOT, 'packages/docs-demos/src/demos');
const OUT = path.join(ROOT, 'packages/docs-demos/src/registry.ts');

const slugs = fs
  .readdirSync(DEMO_DIR)
  .filter((f) => f.endsWith('.tsx'))
  .map((f) => f.replace(/\.tsx$/, ''))
  .sort((a, b) => a.localeCompare(b));

const loaders = slugs
  .map((s) => `  '${s}': () => import('./demos/${s}'),`)
  .join('\n');
const sources = slugs
  .map((s) => `  '${s}': () => import('./demos/${s}.tsx?raw'),`)
  .join('\n');

const file = `/**
 * GENERATED by \`node scripts/generate-demo-registry.mjs\` — do not edit.
 *
 * Every package's demo module, and the demo file's own source. Both are lazy:
 * a reader who opens one package downloads that package's demo chunk and
 * nothing else, which is what keeps a 48-package catalogue cheap to browse.
 */
import type { PackageDemoModule } from './types';

type DemoLoader = () => Promise<{ default: PackageDemoModule }>;
type SourceLoader = () => Promise<{ default: string }>;

const DEMOS: Record<string, DemoLoader> = {
${loaders}
};

/**
 * The demo file's own text, imported with \`?raw\`.
 *
 * The source shown beside a demo is THE FILE THAT JUST RAN, not a copy of it
 * written into a string — which is the only way a snippet cannot drift from the
 * component it claims to produce.
 */
const SOURCES: Record<string, SourceLoader> = {
${sources}
};

/** Every package that ships a demo, alphabetically. */
export const DEMO_SLUGS: string[] = Object.keys(DEMOS).sort((a, b) => a.localeCompare(b));

/** One package's demos, or null when it ships none. */
export async function loadPackageDemos(slug: string): Promise<PackageDemoModule | null> {
  const load = DEMOS[slug];
  if (!load) return null;
  return (await load()).default;
}

/** The raw text of one package's demo file, for the editor. */
export async function loadPackageDemoSource(slug: string): Promise<string> {
  const load = SOURCES[slug];
  if (!load) return '';
  return (await load()).default;
}
`;

const check = process.argv.includes('--check');
const current = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8').replaceAll('\r\n', '\n') : '';
if (check) {
  if (current === file) {
    console.log(`generate-demo-registry: registry.ts matches the demos (${slugs.length} packages).`);
    process.exit(0);
  }
  console.error(
    `generate-demo-registry: registry.ts is out of date (${slugs.length} demo file(s) on disk).\n` +
      'Run `node scripts/generate-demo-registry.mjs` and commit the result.'
  );
  process.exit(1);
}
fs.writeFileSync(OUT, file);
console.log(`generate-demo-registry: wrote ${slugs.length} package(s) to packages/docs-demos/src/registry.ts`);
